@lru_cache(maxsize=1)
def palettes():
    result = {}
    for key, text in RAW_PALETTES.items():
        parser = configparser.ConfigParser(interpolation=None)
        parser.read_string(text)
        meta = parser['Palette']
        variants = {}
        for mode in ('light', 'dark'):
            section = parser[mode.title()] if parser.has_section(mode.title()) else meta
            variants[mode] = {
                'foreground': section['Foreground'], 'background': section['Background'],
                'cursor': section.get('Cursor', section['Foreground']),
                'colors': [section[f'Color{i}'] for i in range(16)]}
        result[key] = dict(name=meta['Name'], primary=meta.getboolean('Primary', False),
                           adaptive=parser.has_section('Light'), **variants)
    return result


def palette(key, dark):
    item = palettes().get(key)
    return item['dark' if dark else 'light'] if item else None
